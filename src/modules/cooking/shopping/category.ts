export function guessCategory(name: string): ShoppingCategory {
  const normalized = normalizeItemName(name);
  for (const [category, keywords] of KEYWORDS) {
    if (keywords.some((keyword) => normalized.includes(keyword))) return category;
  }
  return '기타';
}

export function isShoppingCategory(value: string): value is ShoppingCategory {
  return (SHOPPING_CATEGORIES as readonly string[]).includes(value);
}
